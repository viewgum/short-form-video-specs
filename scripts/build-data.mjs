// Writes lib/data.mjs from data/*.json, so the library loads in browsers and bundlers without JSON imports.
import { readFileSync, writeFileSync } from "node:fs";

const read = (name) => JSON.parse(readFileSync(new URL(`../data/${name}.json`, import.meta.url), "utf8"));
const parts = {
  safeZones: read("safe-zones"),
  lengthLimits: read("length-limits"),
  textLimits: read("text-limits"),
  speakingRates: read("speaking-rates"),
};
const body = Object.entries(parts)
  .map(([name, value]) => `export const ${name} = ${JSON.stringify(value, null, 2)};\n`)
  .join("\n");
writeFileSync(new URL("../lib/data.mjs", import.meta.url), `// Generated by scripts/build-data.mjs from data/*.json. Edit the JSON, then run npm run build.\n${body}`);
